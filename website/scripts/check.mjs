import {readFile,access} from 'node:fs/promises';
import assert from 'node:assert/strict';
const html = await readFile('index.html','utf8');
const js = await readFile('app.js','utf8');
for (const match of html.matchAll(/(?:src|href|poster)="(\/[^"#]+)"/g)) await access(`.${match[1].split('?')[0]}`);
for (const theme of ['fern','paper','cobalt','rose','ember','moon','carbon','tide','aurora','glacier','lavender','ink']) await access(`assets/${theme}.webp`);
assert.equal([...html.matchAll(/role="tab"/g)].length,9);
for (const mode of ['time','words','quote','endless','zen','daily','weak','custom','code']) await access(`assets/mode-${mode}.webp`);
const css = await readFile('style.css','utf8');
assert(!/Geist|Menlo|SFMono|Consolas/i.test(css),'Typography must use the chosen website fonts');
assert.equal([...html.matchAll(/href="#install"/g)].length,1,'Keep one hero install action');
assert(html.includes('icons.svg#github-logo'));
const sprite = await readFile('assets/icons.svg','utf8');
for (const icon of html.matchAll(/icons\.svg#([^"]+)/g)) assert(sprite.includes(`id="${icon[1]}"`), `Missing icon ${icon[1]}`);
assert.equal([...html.matchAll(/data-theme=/g)].length,12);
assert.equal([...html.matchAll(/data-install=/g)].length,3);
const installer = await readFile('../scripts/install.sh','utf8');
const version = JSON.parse(await readFile('package.json','utf8')).version;
assert(installer.includes(`TYPEDEF_VERSION:-v${version}`),'Website and installer versions must match');
assert(html.includes(`releases/tag/v${version}`),'Release link must match the package version');
assert(html.includes('https://typedef-tui.vercel.app/install.sh | sh'));
assert(js.includes('brew install rawatpriyansh17/tap/typedef'));
assert(!/No browser required/i.test(html));
assert(!/TODO|lorem ipsum|placeholder/i.test(html));
assert(html.includes('prefers-reduced-motion') || js.includes('prefers-reduced-motion'));
const video = await readFile('assets/demo.mp4');
assert(video.length>10000 && video.subarray(4,8).toString()==='ftyp','Missing/invalid demo video');
console.log('Verified local links, media, mode controls and theme assets.');
